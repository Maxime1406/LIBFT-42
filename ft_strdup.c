#include "libft.h"

static char	*ft_strcpy(char *dest, const char *src)
{
	int	i;

	i = 0;
	while (src[i])
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}

char	*ft_strdup(const char *s)
{
	char	*dest;
	size_t	len_str;

	len_str = ft_strlen(s);
	dest = malloc(sizeof(char) * (len_str + 1));
	if (!dest)
		return (NULL);
	dest = ft_strcpy(dest, s);
	return (dest);
}
