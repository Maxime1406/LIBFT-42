#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	size_t	i;
	size_t	len_s;

	i = 0;
	len_s = ft_strlen(s);
	while (len_s + 1 > i)
	{
		if (s[len_s] == (char)c)
			return ((char *)&s[len_s]);
		len_s--;
	}
	return (0);
}
